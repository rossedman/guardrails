const testsSource = `package codec

import "testing"

type helper struct{}

func (helper) BenchmarkMethod(b *testing.B) { Sum(nil) }

func BenchmarkSum(b *testing.B) {
	for b.Loop() {
		Sum([]int{1, 2})
	}
}

func BenchmarkSub(b *testing.B) {
	b.Run("drain", func(b *testing.B) {
		q := &Queue{}
		q.Drain()
	})
}

func BenchmarkGeneric(b *testing.B) {
	_ = Map[int](nil)
}

func BenchmarkTooManyParams(b *testing.B, x int) {}

func FuzzParseConfig(f *testing.F) {
	f.Add([]byte("{}"))
	f.Fuzz(func(t *testing.T, data []byte) {
		_, _ = ParseConfig(data)
	})
}

func TestNotIndexed(t *testing.T) { Sum(nil) }

func Benchmark(b *testing.B)
`

func TestIndexTests(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	writeFile(t, dir, "codec_test.go", testsSource)
	writeFile(t, dir, "codec.go", "package codec\n")
	idx, err := IndexTests(dir)
	if err != nil {
		t.Fatal(err)
	}
	var benches, fuzz []string
	for n := range idx.Benchmarks {
		benches = append(benches, n)
	}
	for n := range idx.Fuzz {
		fuzz = append(fuzz, n)
	}
	slices.Sort(benches)
	if want := []string{"BenchmarkGeneric", "BenchmarkSub", "BenchmarkSum"}; !slices.Equal(benches, want) {
		t.Errorf("benchmarks = %v, want %v", benches, want)
	}
	if !slices.Equal(fuzz, []string{"FuzzParseConfig"}) {
		t.Errorf("fuzz = %v", fuzz)
	}
	if idx.Files["BenchmarkSum"] != filepath.Join(dir, "codec_test.go") {
		t.Errorf("Files = %v", idx.Files)
	}
	for _, tc := range []struct {
		set   map[string]map[string]bool
		test  string
		calls string
	}{
		{idx.Benchmarks, "BenchmarkSum", "Sum"},
		{idx.Benchmarks, "BenchmarkSub", "Drain"},
		{idx.Benchmarks, "BenchmarkGeneric", "Map"},
		{idx.Fuzz, "FuzzParseConfig", "ParseConfig"},
	} {
		if !tc.set[tc.test][tc.calls] {
			t.Errorf("%s should call %s: %v", tc.test, tc.calls, tc.set[tc.test])
		}
	}

	sum := Func{Ident: "Sum"}
	if got := Covering(idx.Benchmarks, sum); !slices.Equal(got, []string{"BenchmarkSum"}) {
		t.Errorf("Covering(Sum) = %v", got)
	}
	if got := Covering(idx.Fuzz, sum); len(got) != 0 {
		t.Errorf("Covering fuzz(Sum) = %v", got)
	}
	multi := map[string]map[string]bool{"BenchmarkB": {"F": true}, "BenchmarkA": {"F": true}}
	if got := Covering(multi, Func{Ident: "F"}); !slices.Equal(got, []string{"BenchmarkA", "BenchmarkB"}) {
		t.Errorf("Covering sorted = %v", got)
	}
}


// mutEnv builds an Env over a Fake whose "go test" calls are decided by
// decide (given the mutant source, or nil for the baseline run).
func mutEnv(root string, decide func(mutant []byte) (runner.Result, error)) (Env, *runner.Fake) {
	f := runner.NewFake("go")
	f.OnFunc("go test", func(c runner.Call) (runner.Result, error) {
		for _, a := range c.Args {
			path, ok := strings.CutPrefix(a, "-overlay=")
			if !ok {
				continue
			}
			var ov struct{ Replace map[string]string }
			data, err := os.ReadFile(path)
			if err != nil {
				return runner.Result{}, err
			}
			if err := json.Unmarshal(data, &ov); err != nil {
				return runner.Result{}, err
			}
			for _, mutant := range ov.Replace {
				src, err := os.ReadFile(mutant)
				if err != nil {
					return runner.Result{}, err
				}
				return decide(src)
			}
		}
		return decide(nil)
	})
	cfg := config.Default()
	e := Env{Env: module.Env{Runner: f, Config: cfg, Repo: root}, Root: root}
	return e, f
}

const mutMaxSrc = "package pkg\n\nfunc Max(a, b int) int {\n\tif a > b {\n\t\treturn a\n\t}\n\treturn b\n}\n"

func TestMutationReportsSurvivors(t *testing.T) {
	t.Parallel()
	root, funcs := mutFixture(t, mutMaxSrc)
	e, _ := mutEnv(root, func(m []byte) (runner.Result, error) {
		switch {
		case m == nil:
			return runner.Result{}, nil
		case strings.Contains(string(m), "a >= b"):
			return runner.Result{}, nil // survives
		default:
			return runner.Result{ExitCode: 1, Stdout: "--- FAIL: TestMax"}, nil
		}
	})
	res := Mutation(context.Background(), e, funcs)
	if len(res.Ran) != 1 || res.Ran[0] != "mutation" {
		t.Fatalf("ran = %v", res.Ran)
	}
	if len(res.Checks) != 1 {
		t.Fatalf("checks = %+v notes = %v", res.Checks, res.Notes)
	}
	c := res.Checks[0]
	if c.Name != "mutation" || !c.Failed || c.Summary != "mutation score 50% < 70% (1 of 2 mutants killed)" {
		t.Errorf("summary = %q", c.Summary)
	}
	if len(c.Lines) != 1 || c.Lines[0] != "pkg/x.go:4  Max  `>` changed to `>=`, tests still pass" {
		t.Errorf("lines = %q", c.Lines)
	}
	if c.Fix == "" {
		t.Error("missing fix")
	}
}

func TestMutationClassification(t *testing.T) {
	t.Parallel()
	root, funcs := mutFixture(t, mutMaxSrc)
	e, _ := mutEnv(root, func(m []byte) (runner.Result, error) {
		switch {
		case m == nil:
			return runner.Result{}, nil
		case strings.Contains(string(m), "a >= b"):
			return runner.Result{}, context.DeadlineExceeded // timed out: killed
		default:
			return runner.Result{ExitCode: 1, Stdout: "FAIL example.com/m/pkg [build failed]"}, nil
		}
	})
	res := Mutation(context.Background(), e, funcs)
	if len(res.Checks) != 0 || len(res.Ran) != 1 {
		t.Fatalf("checks = %+v ran = %v", res.Checks, res.Ran)
	}

	// Only non-viable mutants: ran, but nothing to score.
	e2, _ := mutEnv(root, func(m []byte) (runner.Result, error) {
		if m == nil {
			return runner.Result{}, nil
		}
		return runner.Result{}, errors.New("exec failed")
	})
	res = Mutation(context.Background(), e2, funcs)
	if len(res.Checks) != 0 || len(res.Ran) != 1 {
		t.Fatalf("not viable: %+v", res)
	}
}


package gofiles

import (
	"errors"
	"os"
	"path/filepath"
	"reflect"
	"testing"
)

// write creates files under dir, making their directories.
func write(t *testing.T, dir string, files map[string]string) {
	t.Helper()
	for name, body := range files {
		p := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func TestWalk(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	write(t, dir, map[string]string{
		"a.go":              "package a\n",
		"a_test.go":         "package a\n",
		"notes.txt":         "not go\n",
		"sub/b.go":          "// Code generated by hand. DO NOT EDIT.\n\npackage sub\n",
		"sub/testdata/c.go": "package c\n",
		"vendor/v/v.go":     "package v\n",
		".hidden/h.go":      "package h\n",
		"_skip/s.go":        "package s\n",
		"sub/deeper/d.go":   "package deeper\n",
	})
	walk := func(patterns ...string) (got []string, generated []string) {
		t.Helper()
		err := Walk(patterns, func(f File) error {
			rel, _ := filepath.Rel(dir, f.Path)
			got = append(got, filepath.ToSlash(rel))
			if f.Generated() {
				generated = append(generated, filepath.ToSlash(rel))
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
		return got, generated
	}

	got, gen := walk(dir + "/...")
	if want := []string{"a.go", "sub/b.go", "sub/deeper/d.go"}; !reflect.DeepEqual(got, want) {
		t.Errorf("recursive = %v, want %v", got, want)
	}
	if want := []string{"sub/b.go"}; !reflect.DeepEqual(gen, want) {
		t.Errorf("generated = %v, want %v", gen, want)
	}
	if got, _ := walk(dir, dir); !reflect.DeepEqual(got, []string{"a.go"}) {
		t.Errorf("one directory, listed twice = %v", got)
	}
}

func TestWalkDotDotDot(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, map[string]string{"x/x.go": "package x\n"})
	t.Chdir(dir)
	var got []string
	if err := Walk([]string{"..."}, func(f File) error { got = append(got, f.Path); return nil }); err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(got, []string{filepath.Join("x", "x.go")}) {
		t.Errorf("... = %v", got)
	}
}

func TestWalkErrors(t *testing.T) {
	t.Parallel()
	if err := Walk([]string{filepath.Join(t.TempDir(), "missing")}, func(File) error { return nil }); err == nil {
		t.Error("a missing directory is not an error")
	}
	dir := t.TempDir()
	write(t, dir, map[string]string{"bad.go": "package\n"})
	if err := Walk([]string{dir}, func(File) error { return nil }); err == nil {
		t.Error("a file that doesn't parse is not an error")
	}
	write(t, dir, map[string]string{"bad.go": "package ok\n"})
	stop := errors.New("stop")
	if err := Walk([]string{dir}, func(File) error { return stop }); !errors.Is(err, stop) {
		t.Errorf("callback error = %v", err)
	}
}

func TestModulePath(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	write(t, dir, map[string]string{"go.mod": "// comment\nmodule \"example.com/m\"\n\ngo 1.26\n"})
	if got, err := ModulePath(dir); err != nil || got != "example.com/m" {
		t.Errorf("ModulePath = %q, %v", got, err)
	}
	write(t, dir, map[string]string{"go.mod": "go 1.26\n"})
	if _, err := ModulePath(dir); err == nil {
		t.Error("go.mod without a module line is not an error")
	}
	if _, err := ModulePath(t.TempDir()); err == nil {
		t.Error("a missing go.mod is not an error")
	}
}

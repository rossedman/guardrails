const codecSource = `package codec

import (
	"encoding/json"
	"errors"
	"sort"
	str "strconv"
)

type Queue struct{ items []int }

type Box[T any] struct{ v T }

// Drain empties the queue.
func (q *Queue) Drain() []int {
	out := q.items
	q.items = nil
	return out
}

func (b Box[T]) Get() T {
	return b.v
}

// guardrails:hot this runs per request
func Hot() int {
	return 1
}

// ParseConfig reads config bytes.
//
// guardrails:nofuzz covered by the integration suite
func ParseConfig(data []byte) (map[string]any, error) {
	var m map[string]any
	if err := json.Unmarshal(data, &m); err != nil {
		return nil, err
	}
	return m, nil
}

// guardrails:nobench trivial
func Sum(xs []int) int {
	t := 0
	for _, x := range xs {
		t += x
	}
	return t
}

func SortNames(names []string) {
	sort.Strings(names)
}

func Unused() error {
	return errors.New("x")
}

func Atoi(s string) int {
	n, _ := str.Atoi(s)
	return n
}

func declOnly()
`

func writeFile(t *testing.T, dir, name, content string) string {
	t.Helper()
	p := filepath.Join(dir, name)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	return p
}

func lineSet(lines ...int) coverage.LineSet {
	s := coverage.LineSet{}
	for _, l := range lines {
		s[l] = true
	}
	return s
}

func allLines(content string) coverage.LineSet {
	s := coverage.LineSet{}
	for i := range strings.Split(content, "\n") {
		s[i+1] = true
	}
	return s
}

// lineOf returns the 1-based line of the first occurrence of needle.
func lineOf(t *testing.T, content, needle string) int {
	t.Helper()
	for i, l := range strings.Split(content, "\n") {
		if strings.Contains(l, needle) {
			return i + 1
		}
	}
	t.Fatalf("%q not found", needle)
	return 0
}

func byName(funcs []Func) map[string]Func {
	m := map[string]Func{}
	for _, f := range funcs {
		m[f.Name] = f
	}
	return m
}

func TestChangedFuncs(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	src := writeFile(t, root, "codec/codec.go", codecSource)
	test := writeFile(t, root, "codec/codec_test.go", "package codec\n\nfunc helper() {}\n")
	gen := writeFile(t, root, "codec/gen.go", "// Code generated by x. DO NOT EDIT.\n\npackage codec\n\nfunc G() {}\n")
	missing := filepath.Join(root, "codec/gone.go")
	notGo := writeFile(t, root, "codec/README.md", "hi\n")

	drainBody := lineOf(t, codecSource, "q.items = nil")
	getBody := lineOf(t, codecSource, "return b.v")
	importLine := lineOf(t, codecSource, `"sort"`)
	funcs, err := ChangedFuncs(map[string]coverage.LineSet{
		src:     lineSet(drainBody, getBody, importLine),
		test:    lineSet(3),
		gen:     lineSet(5),
		missing: lineSet(1),
		notGo:   lineSet(1),
	})
	if err != nil {
		t.Fatal(err)
	}
	got := byName(funcs)
	if len(got) != 2 {
		t.Fatalf("funcs = %v", funcs)
	}
	drain, ok := got["(*Queue).Drain"]
	if !ok || drain.Ident != "Drain" || drain.Dir != filepath.Dir(src) || drain.File != src {
		t.Fatalf("drain = %+v", drain)
	}
	if !slices.Equal(drain.Changed, []int{drainBody}) || drain.Start >= drain.End {
		t.Errorf("drain span = %d-%d changed %v", drain.Start, drain.End, drain.Changed)
	}
	if _, ok := got["(Box).Get"]; !ok {
		t.Errorf("generic receiver not named like go tool cover: %v", funcs)
	}
	d, file, fset := drain.Decl()
	if d == nil || file == nil || fset == nil || d.Name.Name != "Drain" {
		t.Error("Decl() lost the parsed declaration")
	}
}

func TestChangedFuncsAnnotations(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	src := writeFile(t, root, "codec/codec.go", codecSource)
	funcs, err := ChangedFuncs(map[string]coverage.LineSet{src: allLines(codecSource)})
	if err != nil {
		t.Fatal(err)
	}
	got := byName(funcs)
	if _, ok := got["declOnly"]; ok {
		t.Error("body-less declarations must be skipped")
	}
	tests := []struct {
		fn   string
		want map[string]string
	}{
		{"Hot", map[string]string{"hot": "this runs per request"}},
		{"ParseConfig", map[string]string{"nofuzz": "covered by the integration suite"}},
		{"Sum", map[string]string{"nobench": "trivial"}},
		{"Unused", map[string]string{}},
	}
	for _, tc := range tests {
		f, ok := got[tc.fn]
		if !ok {
			t.Fatalf("%s not found", tc.fn)
		}
		if len(f.Annotations) != len(tc.want) {
			t.Errorf("%s annotations = %v, want %v", tc.fn, f.Annotations, tc.want)
		}
		for k, v := range tc.want {
			if f.Annotations[k] != v {
				t.Errorf("%s[%s] = %q, want %q", tc.fn, k, f.Annotations[k], v)
			}
		}
	}
}

func TestAnnotationOnLineAboveWithoutDoc(t *testing.T) {
	t.Parallel()
	// A directive separated from the declaration by a blank line is not a
	// doc comment, but one directly above is.
	src := "package p\n\n// guardrails:hot\n\nfunc A() {}\n\nfunc B() {} // trailing\n"
	path := writeFile(t, t.TempDir(), "p.go", src)
	funcs, err := ChangedFuncs(map[string]coverage.LineSet{path: allLines(src)})
	if err != nil {
		t.Fatal(err)
	}
	got := byName(funcs)
	if len(got["A"].Annotations) != 0 || len(got["B"].Annotations) != 0 {
		t.Errorf("unexpected annotations: %+v", funcs)
	}
}


func TestMutationSkips(t *testing.T) {
	t.Parallel()
	// No sites.
	root, funcs := mutFixture(t, "package pkg\n\nfunc F() int {\n\treturn 1\n}\n")
	e, f := mutEnv(root, func([]byte) (runner.Result, error) { return runner.Result{}, nil })
	if res := Mutation(context.Background(), e, funcs); len(res.Ran)+len(res.Checks)+len(res.Notes) != 0 || len(f.Calls()) != 0 {
		t.Errorf("no sites: %+v", res)
	}

	// Baseline fails.
	root, funcs = mutFixture(t, mutMaxSrc)
	e, _ = mutEnv(root, func([]byte) (runner.Result, error) { return runner.Result{ExitCode: 1}, nil })
	res := Mutation(context.Background(), e, funcs)
	if len(res.Ran) != 0 || len(res.Notes) != 1 || !strings.Contains(res.Notes[0], "do not pass unmutated") {
		t.Errorf("baseline: %+v", res)
	}

	// Source unreadable after analysis.
	root, funcs = mutFixture(t, mutMaxSrc)
	e, _ = mutEnv(root, func([]byte) (runner.Result, error) { return runner.Result{}, nil })
	if err := os.Remove(funcs[0].File); err != nil {
		t.Fatal(err)
	}
	res = Mutation(context.Background(), e, funcs)
	if len(res.Ran) != 0 || len(res.Notes) != 1 || !strings.Contains(res.Notes[0], "skipped") {
		t.Errorf("unreadable: %+v", res)
	}
}

func TestMutationSamplesToBudget(t *testing.T) {
	t.Parallel()
	root, funcs := mutFixture(t, "package pkg\n\nfunc F(a, b int) bool {\n\treturn a < b && a > 0 || b >= a\n}\n")
	e, _ := mutEnv(root, func(m []byte) (runner.Result, error) {
		if m == nil {
			return runner.Result{}, nil
		}
		return runner.Result{ExitCode: 1}, nil
	})
	// The clock jumps 20s per reading, so the baseline looks like 20s and
	// the mutants far exceed the 45s budget.
	var tick atomic.Int64
	base := time.Unix(0, 0)
	e.Now = func() time.Time { return base.Add(time.Duration(tick.Add(1)) * 20 * time.Second) }
	res := Mutation(context.Background(), e, funcs)
	if len(res.Notes) == 0 || !strings.Contains(res.Notes[0], "sampled") || !strings.Contains(res.Notes[0], "45s budget") {
		t.Fatalf("notes = %v", res.Notes)
	}
	if len(res.Ran) != 1 {
		t.Errorf("ran = %v", res.Ran)
	}
}

func TestMutationBudgetRunsOut(t *testing.T) {
	root, funcs := mutFixture(t, "package pkg\n\nfunc F(a, b int) bool {\n\treturn a < b && a > 0\n}\n")
	e, _ := mutEnv(root, func(m []byte) (runner.Result, error) {
		if m == nil {
			return runner.Result{}, nil
		}
		time.Sleep(400 * time.Millisecond)
		return runner.Result{ExitCode: 1}, nil
	})
	e.Config.Go.Mutation.BudgetSeconds = 1
	old := mutWorkers
	mutWorkers = func() int { return 1 }
	t.Cleanup(func() { mutWorkers = old })
	res := Mutation(context.Background(), e, funcs)
	found := false
	for _, n := range res.Notes {
		if strings.Contains(n, "budget ran out after") {
			found = true
		}
	}
	if !found {
		t.Fatalf("notes = %v", res.Notes)
	}
}


package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// writeFile creates name under dir with body.
func writeFile(t *testing.T, dir, name, body string) {
	t.Helper()
	p := filepath.Join(dir, name)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestRun(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	writeFile(t, dir, "ok/ok.go", "// Package ok is documented.\npackage ok\n\n// F is documented.\nfunc F() {}\n")
	writeFile(t, dir, "bad/bad.go", `package bad

func plain() {}

type T[K any] struct{}

func (t *T[K]) Ptr() {}

func (T[K]) Val() {}

type U[K, V any] struct{}

func (U[K, V]) Multi() {}

// Doc is documented.
func Doc() {}
`)
	writeFile(t, dir, "gen/gen.go", "// Code generated by x. DO NOT EDIT.\n\npackage gen\n\nfunc G() {}\n")
	writeFile(t, dir, "bad/bad_test.go", "package bad\n\nfunc helper() {}\n")

	var out, errOut bytes.Buffer
	if code := run([]string{dir + "/..."}, &out, &errOut); code != 1 {
		t.Fatalf("run = %d, stderr %q", code, errOut.String())
	}
	got := out.String()
	for _, want := range []string{"bad.go: plain has", "bad.go: T.Ptr has", "bad.go: T.Val has", "bad.go: U.Multi has", "bad: package has no package comment", "doccheck: 5 missing"} {
		if !strings.Contains(got, want) {
			t.Errorf("output lacks %q:\n%s", want, got)
		}
	}
	for _, unwanted := range []string{"Doc", "helper", "gen", "ok"} {
		if strings.Contains(got, unwanted+" has") || strings.Contains(got, string(filepath.Separator)+unwanted+": package") {
			t.Errorf("output reports %q:\n%s", unwanted, got)
		}
	}

	out.Reset()
	if code := run([]string{filepath.Join(dir, "ok")}, &out, &errOut); code != 0 || out.Len() != 0 {
		t.Errorf("documented package: %d %q", code, out.String())
	}
	if code := run([]string{filepath.Join(dir, "missing")}, &out, &errOut); code != 2 || !strings.Contains(errOut.String(), "doccheck:") {
		t.Errorf("missing dir: %d %q", code, errOut.String())
	}
}

func TestRunDefaultsToTheModule(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, dir, "a/a.go", "// Package a is documented.\npackage a\n")
	t.Chdir(dir)
	var out, errOut bytes.Buffer
	if code := run(nil, &out, &errOut); code != 0 {
		t.Errorf("run = %d: %s%s", code, out.String(), errOut.String())
	}
}


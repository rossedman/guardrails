func TestMutationIntegration(t *testing.T) {
	if testing.Short() {
		t.Skip("runs go test against mutants")
	}
	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("go not installed")
	}
	weak := "package pkg\n\nimport \"testing\"\n\nfunc TestAbove(t *testing.T) {\n\tif !Above(2, 1) {\n\t\tt.Fatal(\"above\")\n\t}\n}\n"
	strong := "package pkg\n\nimport \"testing\"\n\nfunc TestAbove(t *testing.T) {\n\tif !Above(2, 1) || Above(1, 1) || Above(1, 2) {\n\t\tt.Fatal(\"above\")\n\t}\n}\n"
	src := "package pkg\n\nfunc Above(a, b int) bool {\n\treturn a > b\n}\n"

	run := func(test string) Result {
		root, funcs := mutFixture(t, src)
		if err := os.WriteFile(filepath.Join(root, "pkg", "x_test.go"), []byte(test), 0o600); err != nil {
			t.Fatal(err)
		}
		e := Env{
			Env:  module.Env{Runner: runner.Exec{}, Config: config.Default(), Repo: root},
			Root: root,
		}
		return Mutation(context.Background(), e, funcs)
	}

	res := run(weak)
	if len(res.Checks) != 1 {
		t.Fatalf("weak test: want a failing check, got %+v", res)
	}
	if len(res.Checks[0].Lines) != 1 || res.Checks[0].Lines[0] != "pkg/x.go:4  Above  `>` changed to `>=`, tests still pass" {
		t.Errorf("survivors = %q", res.Checks[0].Lines)
	}
	if res = run(strong); len(res.Checks) != 0 || len(res.Ran) != 1 {
		t.Fatalf("strong test: %+v", res)
	}
}

// parse returns the changed functions of src (all lines changed), by name.
func parse(t *testing.T, root, rel, src string) map[string]Func {
	t.Helper()
	path := writeFile(t, root, rel, src)
	funcs, err := ChangedFuncs(map[string]coverage.LineSet{path: allLines(src)})
	if err != nil {
		t.Fatal(err)
	}
	return byName(funcs)
}

func TestHotPath(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	got := parse(t, root, "internal/codec/codec.go", codecSource)
	plain := parse(t, root, "other/plain.go", `package other

import "strings"

func Plain(n int) int {
	for i := 0; i < n; i++ {
		_ = i
	}
	return n
}

func Map(m map[string]int, xs ...int) int {
	for range m {
	}
	for range xs {
	}
	return 0
}

func Str(s string) int {
	n := 0
	for range s {
		n++
	}
	return n
}

func Nested(in struct{ x []int }) int {
	for range in.x {
	}
	return len(strings.Fields(""))
}

func Ptr(p *[]int) {
	for range *p {
	}
}

func HashAll(xs []string) int {
	n := 0
	for range xs {
		n++
	}
	return n
}
`)

	tests := []struct {
		name    string
		f       Func
		perf    []string
		strong  bool
		reasons []string
	}{
		{"annotation", got["Hot"], nil, true, []string{"marked // guardrails:hot"}},
		{"perf exact", got["Unused"], []string{"internal/codec"}, true, []string{"package is listed in go.bench.packages"}},
		{"perf dot slash", got["Unused"], []string{"./internal/codec"}, true, []string{"package is listed in go.bench.packages"}},
		{"perf glob", got["Unused"], []string{"internal/*"}, true, []string{"package is listed in go.bench.packages"}},
		{"perf recursive", got["Unused"], []string{"internal/..."}, true, []string{"package is listed in go.bench.packages"}},
		{"perf no match", got["Unused"], []string{"cmd/...", "internal/codecs"}, false, nil},
		{"name pattern", got["ParseConfig"], nil, false, []string{"ParseConfig parses", "uses encoding/json"}},
		{"name and import", got["SortNames"], nil, false, []string{"SortNames sorts", "uses sort"}},
		{"name and loop", plain["HashAll"], nil, false, []string{"HashAll hashes", "loops over caller-sized input"}},
		{"import alone is not a signal", got["Atoi"], nil, false, nil},
		{"loop alone is not a signal", got["Sum"], nil, false, nil},
		{"loop over map and variadic alone", plain["Map"], nil, false, nil},
		{"counted loop", plain["Plain"], nil, false, nil},
		{"field loop and non-hot import", plain["Nested"], nil, false, nil},
		{"pointer param", plain["Ptr"], nil, false, nil},
		{"imported but unused in body", got["Unused"], nil, false, nil},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			s := HotPath(tc.f, root, tc.perf)
			if s.Strong != tc.strong || !slices.Equal(s.Reasons, tc.reasons) {
				t.Errorf("HotPath = %+v, want strong=%v reasons=%q", s, tc.strong, tc.reasons)
			}
			if s.Any() != (len(tc.reasons) > 0) {
				t.Errorf("Any = %v", s.Any())
			}
		})
	}

	// Loops count only over slice, map, variadic and string parameters.
	for name, want := range map[string]bool{"Map": true, "Str": true, "HashAll": true, "Plain": false, "Nested": false, "Ptr": false} {
		if got := loopsOverInput(plain[name].decl); got != want {
			t.Errorf("loopsOverInput(%s) = %v, want %v", name, got, want)
		}
	}

	// A root the package is not under never matches perf packages.
	if s := HotPath(got["Unused"], "/elsewhere", []string{"internal/codec"}); s.Any() {
		t.Errorf("unrelated root matched: %+v", s)
	}
}


// mutFixture writes src as pkg/x.go in a temp module and returns its
// changed functions, with every line of the file marked changed.
func mutFixture(t *testing.T, src string) (root string, funcs []Func) {
	t.Helper()
	root = t.TempDir()
	if err := os.WriteFile(filepath.Join(root, "go.mod"), []byte("module example.com/m\n\ngo 1.22\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	dir := filepath.Join(root, "pkg")
	if err := os.MkdirAll(dir, 0o700); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(dir, "x.go")
	if err := os.WriteFile(path, []byte(src), 0o600); err != nil {
		t.Fatal(err)
	}
	lines := coverage.LineSet{}
	for i := 1; i <= strings.Count(src, "\n")+1; i++ {
		lines[i] = true
	}
	funcs, err := ChangedFuncs(map[string]coverage.LineSet{path: lines})
	if err != nil {
		t.Fatal(err)
	}
	return root, funcs
}

func mutDescs(funcs []Func) []string {
	var out []string
	for _, f := range funcs {
		for _, s := range mutSites(f) {
			out = append(out, s.Desc())
		}
	}
	sort.Strings(out)
	return out
}

func TestMutationSites(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name string
		body string
		want []string
	}{
		{"less", "return a < b", []string{"`<` changed to `<=`", "`<` changed to `>=`"}},
		{"less equal", "return a <= b", []string{"`<=` changed to `<`", "`<=` changed to `>`"}},
		{"greater", "return a > b", []string{"`>` changed to `<=`", "`>` changed to `>=`"}},
		{"greater equal", "return a >= b", []string{"`>=` changed to `<`", "`>=` changed to `>`"}},
		{"equal", "return a == b", []string{"`==` changed to `!=`"}},
		{"not equal", "return a != b", []string{"`!=` changed to `==`"}},
		{"logical", "return a > 0 && b > 0 || a < b", []string{
			"`&&` changed to `||`", "`<` changed to `<=`", "`<` changed to `>=`",
			"`>` changed to `<=`", "`>` changed to `<=`", "`>` changed to `>=`", "`>` changed to `>=`",
			"`||` changed to `&&`",
		}},
		{"bools", "return true != false", []string{"`!=` changed to `==`", "`false` changed to `true`", "`true` changed to `false`"}},
		{"not", "return !(a == b)", []string{"`!` removed", "`==` changed to `!=`"}},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			_, funcs := mutFixture(t, "package pkg\n\nfunc F(a, b int) bool {\n\t"+tc.body+"\n}\n")
			got := mutDescs(funcs)
			if strings.Join(got, "|") != strings.Join(tc.want, "|") {
				t.Errorf("got %q\nwant %q", got, tc.want)
			}
		})
	}
}

func TestMutationSitesArithmetic(t *testing.T) {
	t.Parallel()
	_, funcs := mutFixture(t, `package pkg

func F(a, b int) int {
	s := "x" + "y"
	s += "z"
	_ = s
	a++
	b--
	a += 1
	b -= 1
	return -(a + b - a*b/a%b)
}
`)
	want := []string{
		"`%` changed to `*`", "`*` changed to `/`", "`+=` changed to `-=`", "`++` changed to `--`",
		"`+` changed to `-`", "`-` changed to `+`", "`--` changed to `++`", "`-` removed",
		"`-=` changed to `+=`", "`/` changed to `*`",
	}
	sort.Strings(want)
	if got := mutDescs(funcs); strings.Join(got, "|") != strings.Join(want, "|") {
		t.Errorf("got %q\nwant %q", got, want)
	}
}

func TestMutationSitesOnlyChangedLines(t *testing.T) {
	t.Parallel()
	_, funcs := mutFixture(t, "package pkg\n\nfunc F(a, b int) bool {\n\tx := a < b\n\treturn x == true\n}\n")
	f := funcs[0]
	f.Changed = []int{5}
	got := mutDescs([]Func{f})
	want := []string{"`==` changed to `!=`", "`true` changed to `false`"}
	if strings.Join(got, "|") != strings.Join(want, "|") {
		t.Errorf("got %q", got)
	}
}

func TestMutationSitesGeneratedAndEmpty(t *testing.T) {
	t.Parallel()
	if s := mutSites(Func{}); s != nil {
		t.Errorf("empty func: %v", s)
	}
	src := "// Code generated by x. DO NOT EDIT.\n\npackage pkg\n\nfunc F(a int) bool { return a < 1 }\n"
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "gen.go", src, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	f := Func{Changed: []int{5}, file: file, fset: fset}
	f.decl = file.Decls[0].(*ast.FuncDecl)
	if s := mutSites(f); s != nil {
		t.Errorf("generated: %v", s)
	}
}

func TestMutApplyAndSample(t *testing.T) {
	t.Parallel()
	src := []byte("return a < b")
	s := mutSite{Off: 9, End: 10, Old: "<", New: "<="}
	if got := string(mutApply(src, s)); got != "return a <= b" {
		t.Errorf("apply = %q", got)
	}
	rm := mutSite{Off: 7, End: 8, Old: "a", Remove: true}
	if got := string(mutApply(src, rm)); got != "return  < b" {
		t.Errorf("remove = %q", got)
	}
	var sites []mutSite
	for i := 0; i < 10; i++ {
		sites = append(sites, mutSite{Line: i})
	}
	if got := mutSample(sites, 3); len(got) != 3 || got[1].Line != 4 {
		t.Errorf("sample = %+v", got)
	}
	if got := mutSample(sites, 0); len(got) != 10 {
		t.Errorf("sample 0 = %d", len(got))
	}
	if got := mutSample(sites, 20); len(got) != 10 {
		t.Errorf("sample 20 = %d", len(got))
	}
	sorted := []mutSite{
		{Func: Func{File: "b"}, Line: 1},
		{Func: Func{File: "a"}, Line: 2, Col: 3},
		{Func: Func{File: "a"}, Line: 2, Col: 1, New: "z"},
		{Func: Func{File: "a"}, Line: 2, Col: 1, New: "y"},
		{Func: Func{File: "a"}, Line: 1},
	}
	mutSort(sorted)
	var order []string
	for _, s := range sorted {
		order = append(order, s.Func.File+s.New)
	}
	if strings.Join(order, ",") != "a,ay,az,a,b" {
		t.Errorf("sort = %v", order)
	}
}


package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// writeFile creates name under dir with body.
func writeFile(t *testing.T, dir, name, body string) {
	t.Helper()
	p := filepath.Join(dir, name)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestRun(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, dir, "go.mod", "module example.com/m\n")
	writeFile(t, dir, "api/types.gen.go", "// Code generated by oapi-codegen. DO NOT EDIT.\n\npackage api\n")
	writeFile(t, dir, "api/handler.go", "package api\n")
	t.Chdir(dir)

	var out, errOut bytes.Buffer
	if code := run(".", nil, &out, &errOut); code != 0 || out.String() != "example.com/m/api/types.gen.go\n" {
		t.Errorf("run = %d %q %q", code, out.String(), errOut.String())
	}

	out.Reset()
	if code := run(".", []string{"missing/..."}, &out, &errOut); code != 2 || !strings.Contains(errOut.String(), "generated:") {
		t.Errorf("missing dir: %d %q", code, errOut.String())
	}
	errOut.Reset()
	if code := run(t.TempDir(), nil, &out, &errOut); code != 2 || !strings.Contains(errOut.String(), "go.mod") {
		t.Errorf("no go.mod: %d %q", code, errOut.String())
	}
}

func TestRunOutsideRoot(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, dir, "go.mod", "module example.com/m\n")
	writeFile(t, dir, "g.go", "// Code generated by x. DO NOT EDIT.\n\npackage m\n")
	var out, errOut bytes.Buffer
	// An absolute pattern under a relative root can't be made relative.
	t.Chdir(dir)
	if code := run(".", []string{dir}, &out, &errOut); code != 2 {
		t.Errorf("run = %d %q %q", code, out.String(), errOut.String())
	}
}
